/**
 * @author Oblx <code@oblx.dev>
 * @description Static Site Generator (SSG) compiler converting docs/*.md (excluding skills/ and 08-sprints/) into src/config/help/tome.ssg.ts.
 */
import { writeFileSync } from 'node:fs';
import { compileHelpBookFromDocs, type HelpChapterSpec } from '@core/metamodel/help.engine';

const ROOT = process.cwd();
const DEFAULT_OUT_PATH = `${ROOT}/src/config/help/tome.ssg.ts`;

export function collectTomeMarkdownDocs(docsDir = `${ROOT}/docs`): Record<string, string> {
	const rawDocsMap: Record<string, string> = {};
	const glob = new Bun.Glob('**/*.md');
	for (const rel of Array.from(glob.scanSync({ cwd: docsDir })).sort()) {
		if (rel.startsWith('skills/') || rel.startsWith('08-sprints/')) continue;
		rawDocsMap[`/docs/${rel}`] = '';
	}
	return rawDocsMap;
}

export async function loadTomeMarkdownDocsAsync(docsDir = `${ROOT}/docs`): Promise<Record<string, string>> {
	const rawDocsMap: Record<string, string> = {};
	const glob = new Bun.Glob('**/*.md');
	for (const rel of Array.from(glob.scanSync({ cwd: docsDir })).sort()) {
		if (rel.startsWith('skills/') || rel.startsWith('08-sprints/')) continue;
		rawDocsMap[`/docs/${rel}`] = await Bun.file(`${docsDir}/${rel}`).text();
	}
	return rawDocsMap;
}

export function buildSsgTomeModuleSource(chapters: readonly HelpChapterSpec[]): string {
	const lines: string[] = [
		'/**',
		' * @author Oblx <code@oblx.dev>',
		' * @description Precompiled Static SSG Field Tome Chapters (auto-generated by bun run build:tome; zero runtime import.meta.glob).',
		' */',
		"import type { HudViewMode } from '@config/constants';",
		"import type { HelpLearningStage, HelpSkillTier, HelpTargetAnchorId, TooltipPlacement } from '@config/registries/help.registry';",
		'',
		'export interface SsgSubStepSpec { readonly id: string; readonly chapterId: string; readonly stepCode: string; readonly title: string; readonly keyTakeaway: string; readonly formulas: readonly string[]; readonly bullets: ReadonlyArray<{ readonly term: string; readonly detail: string }>; readonly tableHeaders: readonly string[]; readonly tableRows: ReadonlyArray<readonly string[]>; readonly actionDrill: string; readonly anchorId: HelpTargetAnchorId; readonly recommendedView: HudViewMode; readonly tooltipPlacement: TooltipPlacement; }',
		'export interface SsgChapterSpec { readonly id: string; readonly docCode: string; readonly docPath: string; readonly order: number; readonly tier: HelpSkillTier; readonly stage: HelpLearningStage; readonly domainLabel: string; readonly title: string; readonly summary: string; readonly shortcutKey: string; readonly anchorId: HelpTargetAnchorId; readonly recommendedView: HudViewMode; readonly tooltipPlacement: TooltipPlacement; readonly actionDrill: string; readonly subSteps: readonly SsgSubStepSpec[]; }',
		'',
		'export const TOME_SSG_CHAPTERS: readonly SsgChapterSpec[] = [',
	];
	for (const ch of chapters) {
		lines.push(`\t${JSON.stringify(ch)},`);
	}
	lines.push('];');
	lines.push('');
	return lines.join('\n');
}

export async function compileTomeSsgFile(outPath = DEFAULT_OUT_PATH, docsDir = `${ROOT}/docs`): Promise<readonly HelpChapterSpec[]> {
	const rawDocs = await loadTomeMarkdownDocsAsync(docsDir);
	const chapters = compileHelpBookFromDocs(rawDocs);
	writeFileSync(outPath, buildSsgTomeModuleSource(chapters), 'utf8');
	return chapters;
}

if (import.meta.main) {
	const chapters = await compileTomeSsgFile();
	console.log(`[chronos:build:tome] Compiled ${chapters.length} SSG Field Tome chapters -> src/config/help/tome.ssg.ts`);
}
